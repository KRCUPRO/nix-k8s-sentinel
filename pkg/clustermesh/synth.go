package clustermesh

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// SynthesizeHardenedClusterMeshConfig generates a production-hardened Cilium Helm values snippet.
func SynthesizeHardenedClusterMeshConfig(cfg *ClusterMeshConfig) string {
	clusterName := "prod-mesh-1"
	clusterID := 1
	if cfg != nil {
		if cfg.ClusterName != "" {
			clusterName = cfg.ClusterName
		}
		if cfg.ClusterID > 0 {
			clusterID = cfg.ClusterID
		}
	}

	var sb strings.Builder
	sb.WriteString("# Hardened Cilium ClusterMesh Helm Configuration\n")
	sb.WriteString("# Generated by nix-k8s-sentinel (M31)\n")
	sb.WriteString("cluster:\n")
	sb.WriteString(fmt.Sprintf("  name: %s\n", clusterName))
	sb.WriteString(fmt.Sprintf("  id: %d\n\n", clusterID))
	sb.WriteString("clustermesh:\n")
	sb.WriteString("  enableEndpointSlice: true\n")
	sb.WriteString("  apiserver:\n")
	sb.WriteString("    enabled: true\n")
	sb.WriteString("    replicas: 2\n")
	sb.WriteString("    tls:\n")
	sb.WriteString("      auto:\n")
	sb.WriteString("        enabled: true\n")
	sb.WriteString("        method: certmanager\n")
	sb.WriteString("        certValidityDuration: 90\n\n")
	sb.WriteString("encryption:\n")
	sb.WriteString("  enabled: true\n")
	sb.WriteString("  type: wireguard\n")
	sb.WriteString("  nodeEncryption: true\n\n")
	sb.WriteString("bpf:\n")
	sb.WriteString("  lbMapMax: 65536\n")

	return sb.String()
}

// SynthesizeHardenedMeshPolicy generates a CiliumClusterwideNetworkPolicy enforcing cross-cluster tenant boundaries.
func SynthesizeHardenedMeshPolicy(allowedClusterName, namespace string) string {
	if allowedClusterName == "" {
		allowedClusterName = "prod-mesh-2"
	}
	if namespace == "" {
		namespace = "tenant-apps"
	}

	var sb strings.Builder
	sb.WriteString("apiVersion: cilium.io/v2\n")
	sb.WriteString("kind: CiliumClusterwideNetworkPolicy\n")
	sb.WriteString("metadata:\n")
	sb.WriteString(fmt.Sprintf("  name: hardened-clustermesh-tenant-isolation-%s\n", namespace))
	sb.WriteString("spec:\n")
	sb.WriteString("  endpointSelector:\n")
	sb.WriteString("    matchLabels:\n")
	sb.WriteString(fmt.Sprintf("      k8s:io.kubernetes.pod.namespace: %s\n", namespace))
	sb.WriteString("  ingress:\n")
	sb.WriteString("  - fromEndpoints:\n")
	sb.WriteString("    - matchLabels:\n")
	sb.WriteString(fmt.Sprintf("        io.cilium.k8s.policy.cluster: %s\n", allowedClusterName))
	sb.WriteString(fmt.Sprintf("        k8s:io.kubernetes.pod.namespace: %s\n", namespace))
	sb.WriteString("    toPorts:\n")
	sb.WriteString("    - ports:\n")
	sb.WriteString("      - port: \"8443\"\n")
	sb.WriteString("        protocol: TCP\n")

	return sb.String()
}

// SynthesizeMeshAlertRules generates Prometheus alerting rules for ClusterMesh health and encryption.
func SynthesizeMeshAlertRules() string {
	return `groups:
- name: cilium-clustermesh-security.rules
  rules:
  - alert: CiliumClusterMeshSyncLatencyDegraded
    expr: clustermesh_sync_duration_seconds > 5
    for: 2m
    labels:
      severity: warning
      domain: clustermesh
    annotations:
      summary: "Cilium ClusterMesh etcd sync latency exceeds 5 seconds"
      description: "ClusterMesh synchronization latency is {{ $value }}s, indicating network degradation or etcd contention."

  - alert: CiliumClusterMeshRemoteClusterDisconnected
    expr: clustermesh_remote_cluster_connected == 0
    for: 1m
    labels:
      severity: critical
      domain: clustermesh
    annotations:
      summary: "Cilium ClusterMesh lost connection to remote cluster"
      description: "One or more remote federated clusters have been disconnected, risking split-brain service discovery."

  - alert: CiliumClusterMeshUnencryptedTraffic
    expr: rate(cilium_drop_count_total{reason="unencrypted_cross_cluster"}[5m]) > 0
    for: 1m
    labels:
      severity: critical
      domain: clustermesh
    annotations:
      summary: "Unencrypted cross-cluster tunnel traffic intercepted"
      description: "Packets were transmitted across clusters without WireGuard/IPsec encryption."
`
}

// WriteSynthesizedPolicies persists generated ClusterMesh configuration, policy, and alerts to disk.
func WriteSynthesizedPolicies(outDir string, cfg *ClusterMeshConfig) ([]string, error) {
	if outDir == "" {
		outDir = "policies/generated/clustermesh"
	}
	cleanDir := filepath.Clean(outDir)
	if err := os.MkdirAll(cleanDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create synthesis directory %s: %w", cleanDir, err)
	}

	var written []string

	// 1. Helm values
	helmPath := filepath.Join(cleanDir, "clustermesh-helm-hardened.yaml")
	if err := os.WriteFile(helmPath, []byte(SynthesizeHardenedClusterMeshConfig(cfg)), 0644); err != nil {
		return nil, fmt.Errorf("failed to write helm values: %w", err)
	}
	written = append(written, helmPath)

	// 2. Network policy
	policyPath := filepath.Join(cleanDir, "clustermesh-isolation-policy.yaml")
	if err := os.WriteFile(policyPath, []byte(SynthesizeHardenedMeshPolicy("prod-mesh-remote", "tenant-prod")), 0644); err != nil {
		return nil, fmt.Errorf("failed to write network policy: %w", err)
	}
	written = append(written, policyPath)

	// 3. Prometheus alerts
	alertPath := filepath.Join(cleanDir, "clustermesh-alerts.yaml")
	if err := os.WriteFile(alertPath, []byte(SynthesizeMeshAlertRules()), 0644); err != nil {
		return nil, fmt.Errorf("failed to write alert rules: %w", err)
	}
	written = append(written, alertPath)

	return written, nil
}
