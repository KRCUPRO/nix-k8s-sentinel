// GetRuleByID retrieves a single benchmark rule by its ID (e.g., "CIS-1.2.1").
func GetRuleByID(id string) *CISRule {
	normalized := strings.ToUpper(strings.TrimSpace(id))
	for _, r := range AllCISRules() {
		if strings.ToUpper(r.ID) == normalized {
			return &r
		}
	}
	return nil
}

// GetRulesByComponent filters benchmark rules for a specific component.
func GetRulesByComponent(comp ComponentType) []CISRule {
	var matched []CISRule
	for _, r := range AllCISRules() {
		if r.Component == comp {
			matched = append(matched, r)
		}
	}
	return matched
}
