package bench

import (
	"fmt"
	"sort"
	"strings"
)

// SynthesizeNixOSRemediation produces a declarative NixOS hardening module containing exact configuration settings.
func SynthesizeNixOSRemediation(violations []CISViolation) string {
	var b strings.Builder
	b.WriteString("# nixos-cis-hardening.nix\n")
	b.WriteString("# Automated CIS Kubernetes Benchmark Remediation Module\n")
	b.WriteString("# Generated by nix-k8s-sentinel\n\n")
	b.WriteString("{\n")
	b.WriteString("  services.kubernetes = {\n")

	// Group violations by component
	compMap := make(map[ComponentType][]CISViolation)
	for _, v := range violations {
		if v.RemediationNix != "" && !strings.HasPrefix(v.RemediationNix, "#") {
			compMap[v.Component] = append(compMap[v.Component], v)
		}
	}

	// Sort component keys deterministically
	keys := make([]string, 0, len(compMap))
	for k := range compMap {
		keys = append(keys, string(k))
	}
	sort.Strings(keys)

	for _, k := range keys {
		ct := ComponentType(k)
		viols := compMap[ct]
		b.WriteString(fmt.Sprintf("    # --- %s Hardening ---\n", strings.ToUpper(k)))
		seen := make(map[string]bool)
		for _, v := range viols {
			if !seen[v.RemediationNix] {
				seen[v.RemediationNix] = true
				lines := strings.Split(v.RemediationNix, "\n")
				for _, l := range lines {
					if strings.TrimSpace(l) != "" {
						b.WriteString(fmt.Sprintf("    %s\n", strings.TrimSpace(l)))
					}
				}
			}
		}
		b.WriteString("\n")
	}

	b.WriteString("  };\n")
	b.WriteString("}\n")
	return b.String()
}

