// FormatRemediationSummary generates a human-readable CLI summary of required remediation actions.
func FormatRemediationSummary(report *CISAuditReport) string {
	if report == nil || len(report.Violations) == 0 {
		return "[+] Zero CIS benchmark remediation actions required. Cluster is fully hardened.\n"
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("=== CIS BENCHMARK REMEDIATION PLAN (%d Actions) ===\n", len(report.Violations)))
	for i, v := range report.Violations {
		cveTag := ""
		if v.MatchedCVE != "" {
			cveTag = fmt.Sprintf(" [%s]", v.MatchedCVE)
		}
		b.WriteString(fmt.Sprintf("[%d] %s (%s) - %s%s\n", i+1, v.RuleID, v.Severity, v.Title, cveTag))
		b.WriteString(fmt.Sprintf("    Flag: %s (Current: %s | Expected: %s)\n", v.FlagName, v.ActualValue, v.ExpectedValue))
		if v.RemediationNix != "" {
			b.WriteString(fmt.Sprintf("    NixOS Fix: %s\n", strings.ReplaceAll(v.RemediationNix, "\n", " ")))
		}
	}
	return b.String()
}
