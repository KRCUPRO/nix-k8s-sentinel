// SynthesizeNixOSPQCModule generates a declarative NixOS hardening module with OpenSSL 3.4+ OQS provider and GnuTLS PQC groups.
func SynthesizeNixOSPQCModule() string {
	var sb strings.Builder
	sb.WriteString("# Generated by nix-k8s-sentinel: Hardened Post-Quantum Cryptography & CNSA 2.0 Module\n")
	sb.WriteString("{ config, pkgs, lib, ... }:\n\n")
	sb.WriteString("{\n")
	sb.WriteString("  security.pki.certificateFiles = [ ];\n\n")
	sb.WriteString("  # 1. System-wide OpenSSL 3.x Post-Quantum Configuration (FIPS 203 ML-KEM)\n")
	sb.WriteString("  environment.etc.\"ssl/openssl.cnf\".text = ''\n")
	sb.WriteString("    openssl_conf = openssl_init\n\n")
	sb.WriteString("    [openssl_init]\n")
	sb.WriteString("    providers = provider_sect\n")
	sb.WriteString("    ssl_conf = ssl_module\n\n")
	sb.WriteString("    [provider_sect]\n")
	sb.WriteString("    default = default_sect\n")
	sb.WriteString("    oqsprovider = oqsprovider_sect\n\n")
	sb.WriteString("    [default_sect]\n")
	sb.WriteString("    activate = 1\n\n")
	sb.WriteString("    [oqsprovider_sect]\n")
	sb.WriteString("    activate = 1\n\n")
	sb.WriteString("    [ssl_module]\n")
	sb.WriteString("    system_default = ssl_configuration\n\n")
	sb.WriteString("    [ssl_configuration]\n")
	sb.WriteString("    MinProtocol = TLSv1.3\n")
	sb.WriteString("    CipherSuites = TLS_AES_256_GCM_SHA384:TLS_CHACHA20_POLY1305_SHA256\n")
	sb.WriteString("    Groups = X25519MLKEM768:SecP384r1MLKEM1024:x25519_kyber768:P-384:X25519\n")
	sb.WriteString("  '';\n\n")
	sb.WriteString("  # 2. System-wide GnuTLS Priority Policy (CNSA 2.0 Compliant)\n")
	sb.WriteString("  environment.etc.\"crypto-policies/config\".text = ''\n")
	sb.WriteString("    SYSTEM=NONE\n")
	sb.WriteString("    +VERS-TLS1.3\n")
	sb.WriteString("    +AES-256-GCM:+CHACHA20-POLY1305\n")
	sb.WriteString("    +GROUP-X25519-KYBER768:+GROUP-SECP384R1-MLKEM1024:+GROUP-SECP384R1\n")
	sb.WriteString("    +SIGN-ML-DSA-65:+SIGN-ML-DSA-87:+SIGN-ECDSA-SECP384R1-SHA384\n")
	sb.WriteString("  '';\n")
	sb.WriteString("}\n")
	return sb.String()
}

// SynthesizeK8sPQCManifest generates hardened Kubernetes control plane flags for kube-apiserver and etcd.
func SynthesizeK8sPQCManifest(component string) string {
	comp := strings.ToLower(component)
	if comp == "etcd" {
		return strings.TrimSpace(`
# Hardened etcd Static Pod Flags for Post-Quantum TLS 1.3 Mutual Authentication
spec:
  containers:
  - name: etcd
    command:
    - etcd
    - --tls-min-version=VersionTLS13
    - --tls-cipher-suites=TLS_AES_256_GCM_SHA384,TLS_CHACHA20_POLY1305_SHA256
    - --peer-tls-min-version=VersionTLS13
    - --peer-tls-cipher-suites=TLS_AES_256_GCM_SHA384,TLS_CHACHA20_POLY1305_SHA256
    - --tls-key-exchange-groups=X25519MLKEM768,SecP384r1MLKEM1024
    - --client-cert-auth=true
    - --peer-client-cert-auth=true
`) + "\n"
	}

	return strings.TrimSpace(`
# Hardened kube-apiserver Static Pod Flags for Post-Quantum TLS 1.3 & CNSA 2.0
spec:
  containers:
  - name: kube-apiserver
    command:
    - kube-apiserver
    - --tls-min-version=VersionTLS13
    - --tls-cipher-suites=TLS_AES_256_GCM_SHA384,TLS_CHACHA20_POLY1305_SHA256
    - --tls-key-exchange-groups=X25519MLKEM768,SecP384r1MLKEM1024
    - --etcd-tls-min-version=VersionTLS13
    - --etcd-tls-cipher-suites=TLS_AES_256_GCM_SHA384
`) + "\n"
}

// WriteSynthesizedPQCConfig persists synthesized NixOS and Kubernetes PQC policies to disk.
func WriteSynthesizedPQCConfig(outDir string) (map[string]string, error) {
	cleanDir := filepath.Clean(outDir)
	if err := os.MkdirAll(cleanDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create output directory %s: %w", cleanDir, err)
	}

	written := make(map[string]string)

	// 1. Write NixOS PQC module
	nixPath := filepath.Join(cleanDir, "pqc-hardened.nix")
	nixContent := SynthesizeNixOSPQCModule()
	if err := os.WriteFile(nixPath, []byte(nixContent), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", nixPath, err)
	}
	written["nixos-module"] = nixPath

	// 2. Write K8s API server manifest
	k8sPath := filepath.Join(cleanDir, "kube-apiserver-pqc.yaml")
	k8sContent := SynthesizeK8sPQCManifest("kube-apiserver")
	if err := os.WriteFile(k8sPath, []byte(k8sContent), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", k8sPath, err)
	}
	written["kube-apiserver"] = k8sPath

	// 3. Write etcd manifest
	etcdPath := filepath.Join(cleanDir, "etcd-pqc.yaml")
	etcdContent := SynthesizeK8sPQCManifest("etcd")
	if err := os.WriteFile(etcdPath, []byte(etcdContent), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", etcdPath, err)
	}
	written["etcd"] = etcdPath

	return written, nil
}
