package impermanence

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Synthesizer generates declarative hardened NixOS impermanence modules, wipe hooks, and alert rules.
type Synthesizer struct{}

// NewSynthesizer creates a new instance of Synthesizer.
func NewSynthesizer() *Synthesizer {
	return &Synthesizer{}
}

// SynthesizeHardenedNixOSModule generates a declarative, production-grade hardened NixOS impermanence configuration.
func (s *Synthesizer) SynthesizeHardenedNixOSModule(hostName string, persistenceRoot string) string {
	if persistenceRoot == "" {
		persistenceRoot = "/persist"
	}

	return fmt.Sprintf(`# Declarative Hardened NixOS Impermanence & Stateless Root Configuration
# Host: %s
# Generated by nix-k8s-sentinel (Automated Security Policy Synthesis)

{ config, pkgs, lib, ... }:

{
  # 1. Ephemeral Root Filesystem on tmpfs
  fileSystems."/" = {
    device = "none";
    fsType = "tmpfs";
    options = [ "defaults" "size=8G" "mode=755" "nosuid" "nodev" ];
  };

  # 2. Hardened Encrypted Persistence Storage Root
  fileSystems."%s" = {
    device = "/dev/mapper/enc-persist";
    fsType = "ext4";
    neededForBoot = true;
    options = [ "defaults" "noexec" "nosuid" "nodev" ];
  };

  # 3. Kernel Memory Scrubbing & Zeroization on Shutdown
  boot.kernelParams = [
    "init_on_alloc=1"
    "init_on_free=1"
    "page_poison=1"
    "slab_nomerge"
    "slub_debug=P"
  ];

  # 4. Ephemeral Encrypted Swap (Mitigating CVE-2026-61842)
  swapDevices = [
    {
      device = "/dev/disk/by-partlabel/swap";
      randomEncryption = true;
    }
  ];

  # 5. Impermanence Declarations with Restricted Permissions
  environment.persistence."%s" = {
    hideMounts = true;
    directories = [
      "/var/log"
      "/var/lib/nixos"
      "/var/lib/systemd/coredump"
      {
        directory = "/var/lib/kubelet";
        user = "root";
        group = "root";
        mode = "0700";
      }
      {
        directory = "/var/lib/containerd";
        user = "root";
        group = "root";
        mode = "0711";
      }
      {
        directory = "/etc/ssh";
        user = "root";
        group = "root";
        mode = "0755";
      }
    ];
    files = [
      "/etc/machine-id"
      {
        file = "/etc/ssh/ssh_host_ed25519_key";
        parentDirectory = { mode = "0700"; };
      }
      {
        file = "/etc/ssh/ssh_host_rsa_key";
        parentDirectory = { mode = "0700"; };
      }
    ];
  };

  # 6. Ensure Root Directories Exist with Restricted Modes
  systemd.tmpfiles.rules = [
    "d /var/lib/kubelet 0700 root root -"
    "d /var/lib/containerd 0711 root root -"
  ];
}
`, hostName, persistenceRoot, persistenceRoot)
}

// SynthesizeWipeOnRebootHook generates verified shell initrd hooks for ZFS or Btrfs snapshot rollbacks.
func (s *Synthesizer) SynthesizeWipeOnRebootHook(fsType string, poolOrSubvolume string) string {
	var body string
	if strings.ToLower(fsType) == "zfs" {
		if poolOrSubvolume == "" {
			poolOrSubvolume = "rpool/local/root@blank"
		}
		body = fmt.Sprintf(`  # ZFS Blank Snapshot Rollback on Boot
  boot.initrd.postDeviceCommands = lib.mkAfter ''
    zfs rollback -r %s
  '';`, poolOrSubvolume)
	} else {
		if poolOrSubvolume == "" {
			poolOrSubvolume = "/dev/mapper/enc-root"
		}
		body = fmt.Sprintf(`  # Btrfs Subvolume Reset on Boot
  boot.initrd.postDeviceCommands = lib.mkBefore ''
    mkdir -p /mnt
    mount -o subvol=/ %s /mnt
    btrfs subvolume delete /mnt/root
    btrfs subvolume snapshot /mnt/root-blank /mnt/root
    umount /mnt
  '';`, poolOrSubvolume)
	}

	return fmt.Sprintf(`# Boot-Time Stateless Root Sanitization Hook
# Generated by nix-k8s-sentinel

{ lib, ... }:

{
%s
}
`, body)
}

// SynthesizePrometheusAlerts generates Prometheus alert rules monitoring ephemeral storage health.
func (s *Synthesizer) SynthesizePrometheusAlerts() string {
	return `groups:
- name: nixos-impermanence-alerts
  rules:
  - alert: TmpfsRootStorageFillingUp
    expr: (node_filesystem_free_bytes{mountpoint="/"} / node_filesystem_size_bytes{mountpoint="/"}) < 0.15
    for: 5m
    labels:
      severity: critical
      component: impermanence
    annotations:
      summary: "Node ephemeral tmpfs root storage is nearly full (< 15% free)"
      description: "Host {{ $labels.instance }} tmpfs root mount has less than 15% free space remaining, risking imminent host kernel OOM freeze."

  - alert: UnencryptedSwapDetected
    expr: node_memory_SwapTotal_bytes > 0 and node_swap_encrypted == 0
    for: 1m
    labels:
      severity: critical
      component: impermanence
    annotations:
      summary: "Unencrypted swap active on stateless node"
      description: "Host {{ $labels.instance }} has plaintext swap active, violating ephemeral root isolation (CVE-2026-61842)."

  - alert: EphemeralRootWipeFailed
    expr: node_boot_wipe_success == 0
    for: 2m
    labels:
      severity: high
      component: impermanence
    annotations:
      summary: "Stateless boot wipe hook failed to sanitize root"
      description: "Node {{ $labels.instance }} failed to execute blank snapshot rollback or tmpfs initialization on boot."
`
}

// WriteSynthesizedPolicies persists generated configurations to the specified output directory.
func (s *Synthesizer) WriteSynthesizedPolicies(outDir string, hostName string, persistenceRoot string) error {
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory %s: %w", outDir, err)
	}

	nixosMod := s.SynthesizeHardenedNixOSModule(hostName, persistenceRoot)
	if err := os.WriteFile(filepath.Join(outDir, "impermanence-hardened.nix"), []byte(nixosMod), 0644); err != nil {
		return fmt.Errorf("failed to write impermanence-hardened.nix: %w", err)
	}

	wipeHook := s.SynthesizeWipeOnRebootHook("zfs", "rpool/local/root@blank")
	if err := os.WriteFile(filepath.Join(outDir, "wipe-on-reboot-zfs.nix"), []byte(wipeHook), 0644); err != nil {
		return fmt.Errorf("failed to write wipe-on-reboot-zfs.nix: %w", err)
	}

	alerts := s.SynthesizePrometheusAlerts()
	if err := os.WriteFile(filepath.Join(outDir, "impermanence-alerts.yaml"), []byte(alerts), 0644); err != nil {
		return fmt.Errorf("failed to write impermanence-alerts.yaml: %w", err)
	}

	return nil
}
