// SynthesizeHardenedSeccompProfile generates a high-security Kubernetes SeccompProfile rejecting dangerous syscalls.
func SynthesizeHardenedSeccompProfile() *SeccompProfile {
	return &SeccompProfile{
		DefaultAction: ActionErrno,
		Architectures: []string{
			"SCMP_ARCH_X86_64",
			"SCMP_ARCH_AARCH64",
			"SCMP_ARCH_X86",
		},
		Syscalls: []SeccompSyscallRule{
			{
				Names:  SafeStandardSyscalls,
				Action: ActionAllow,
			},
		},
		Flags: []string{
			"SECCOMP_FILTER_FLAG_SPEC_ALLOW",
		},
	}
}

// SynthesizeNixOSSeccompModule generates a hardened NixOS systemd service sandbox module.
func SynthesizeNixOSSeccompModule(serviceName string) string {
	svc := serviceName
	if svc == "" {
		svc = "k8s-workload"
	}

	return fmt.Sprintf(`# Generated by nix-k8s-sentinel BPF Hardening Engine
# Enforces eBPF LSM mandatory access control and declarative systemd seccomp filtering.

{ config, lib, pkgs, ... }:

{
  boot.kernel.sysctl = {
    "kernel.unprivileged_bpf_disabled" = 1;
    "kernel.kptr_restrict" = 2;
  };

  security.lsm = [ "lockdown" "yama" "bpf" "apparmor" ];

  systemd.services."%s".serviceConfig = {
    SystemCallFilter = [
      "@system-service"
      "~@privileged"
      "~@resources"
      "~@reboot"
      "~@module"
      "~@raw-io"
      "~@obsolete"
      "~@swap"
    ];
    SystemCallArchitectures = "native";
    SystemCallErrorNumber = "EPERM";
    ProtectKernelTunables = true;
    ProtectKernelModules = true;
    ProtectControlGroups = true;
    RestrictAddressFamilies = [ "AF_UNIX" "AF_INET" "AF_INET6" ];
    RestrictNamespaces = true;
    LockPersonality = true;
    MemoryDenyWriteExecute = true;
  };
}
`, svc)
}

// SynthesizeEBPFLSMDropPolicy generates declarative eBPF LSM hook declarations to drop raw sockets and trace bursts.
func SynthesizeEBPFLSMDropPolicy() string {
	return `# Generated by nix-k8s-sentinel eBPF LSM Engine
# Attaches to kernel LSM hooks to enforce raw socket restrictions and socket flood rate limits.

apiVersion: security.nix-k8s-sentinel.io/v1alpha1
kind: EBPFLSMPolicy
metadata:
  name: lsm-socket-hardening
  labels:
    app.kubernetes.io/managed-by: nix-k8s-sentinel
spec:
  targetLSMHooks:
    - hook: lsm/socket_create
      action: BlockUnprivilegedRaw
      conditions:
        disallowedTypes:
          - SOCK_RAW
          - AF_PACKET
        rateLimit:
          maxSocketsPerSec: 250
          burstLimit: 300
    - hook: lsm/bpf
      action: RestrictUnprivileged
      conditions:
        requireAdmin: true
    - hook: lsm/bprm_check_security
      action: EnforceExecutableIntegrity
`
}

// WriteSynthesizedPolicies persists the seccomp profile JSON, NixOS module, and eBPF LSM policy to disk.
func WriteSynthesizedPolicies(outputDir string, serviceName string) (map[string]string, error) {
	cleanDir := filepath.Clean(outputDir)
	if err := os.MkdirAll(cleanDir, 0o755); err != nil {
		return nil, fmt.Errorf("failed to create policy output directory %s: %w", cleanDir, err)
	}

	writtenFiles := make(map[string]string)

	// 1. Write Kubernetes Seccomp Profile JSON
	seccompProfile := SynthesizeHardenedSeccompProfile()
	seccompBytes, err := json.MarshalIndent(seccompProfile, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("failed to serialize seccomp profile: %w", err)
	}
	seccompPath := filepath.Join(cleanDir, "seccomp-profile-hardened.json")
	if err := os.WriteFile(seccompPath, seccompBytes, 0o644); err != nil {
		return nil, fmt.Errorf("failed to write seccomp profile to %s: %w", seccompPath, err)
	}
	writtenFiles["seccomp_profile"] = seccompPath

	// 2. Write NixOS Systemd Hardening Module
	nixosModule := SynthesizeNixOSSeccompModule(serviceName)
	nixosPath := filepath.Join(cleanDir, "nixos-bpf-hardening.nix")
	if err := os.WriteFile(nixosPath, []byte(nixosModule), 0o644); err != nil {
		return nil, fmt.Errorf("failed to write NixOS module to %s: %w", nixosPath, err)
	}
	writtenFiles["nixos_module"] = nixosPath

	// 3. Write eBPF LSM Policy
	lsmPolicy := SynthesizeEBPFLSMDropPolicy()
	lsmPath := filepath.Join(cleanDir, "ebpf-lsm-policy.yaml")
	if err := os.WriteFile(lsmPath, []byte(lsmPolicy), 0o644); err != nil {
		return nil, fmt.Errorf("failed to write eBPF LSM policy to %s: %w", lsmPath, err)
	}
	writtenFiles["lsm_policy"] = lsmPath

	return writtenFiles, nil
}
