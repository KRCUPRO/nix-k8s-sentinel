package bgp

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// SynthesizeHardenedCiliumBGPPolicy generates a declarative hardened CiliumBGPPeeringPolicy manifest.
func SynthesizeHardenedCiliumBGPPolicy(policyName string, localASN, peerASN int, peerAddr string, authSecret string) string {
	if policyName == "" {
		policyName = "cilium-bgp-hardened"
	}
	if authSecret == "" {
		authSecret = "cilium-bgp-auth-secret"
	}
	if peerAddr == "" {
		peerAddr = "192.168.100.1/32"
	}
	if localASN == 0 {
		localASN = 65001
	}
	if peerASN == 0 {
		peerASN = 65000
	}

	ttl := 2
	if localASN == peerASN {
		ttl = 1
	}

	return fmt.Sprintf(`apiVersion: cilium.io/v2alpha1
kind: CiliumBGPPeeringPolicy
metadata:
  name: %s
spec:
  nodeSelectors:
    matchLabels:
      kubernetes.io/os: linux
      cilium.io/bgp-speaker: "true"
  virtualRouters:
    - localASN: %d
      exportPodCIDR: true
      exportServiceCIDR: true
      prefixFilters:
        - "10.244.0.0/16"
        - "fd00:10:244::/64"
        - "10.96.0.0/12"
        - "fd00:10:96::/112"
      neighbors:
        - peerAddress: "%s"
          peerASN: %d
          authSecretRef: "%s"
          eBGP:
            multihopTTL: %d
          gracefulRestart:
            enabled: true
            restartTimeSeconds: 120
          holdTimeSeconds: 30
          keepAliveTimeSeconds: 10
          families:
            - "IPv4"
            - "IPv6"
          community: "65000:100"
`, policyName, localASN, peerAddr, peerASN, authSecret, ttl)
}

// SynthesizeHardenedNixOSBGPModule generates a declarative NixOS module with FRR and sysctl hardening.
func SynthesizeHardenedNixOSBGPModule(localASN int, torSwitchSubnet string) string {
	if localASN == 0 {
		localASN = 65001
	}
	if torSwitchSubnet == "" {
		torSwitchSubnet = "192.168.100.0/24"
	}

	return fmt.Sprintf(`# Declarative Production-Hardened NixOS BGP & IPv6 Service Mesh Module
# Generated by nix-k8s-sentinel (BGP Peering Radar)
{ config, pkgs, lib, ... }:

{
  services.frr = {
    enable = true;
    bgp = {
      enable = true;
      localASN = %d;
      config = ''
        router bgp %d
          bgp router-id 192.168.100.10
          no bgp default ipv4-unicast
          bgp graceful-restart
          bgp graceful-restart restart-time 120
          neighbor TOR_PEER peer-group
          neighbor TOR_PEER password "CHANGEME_SECRET_MD5"
          address-family ipv4 unicast
            neighbor TOR_PEER activate
          exit-address-family
          address-family ipv6 unicast
            neighbor TOR_PEER activate
          exit-address-family
      '';
    };
  };

  # Mitigate IPv6 Router Advertisement (RA) spoofing (BGP-RADAR-008)
  boot.kernel.sysctl = {
    "net.ipv6.conf.all.accept_ra" = 0;
    "net.ipv6.conf.default.accept_ra" = 0;
    "net.ipv6.conf.all.forwarding" = 1;
    "net.ipv4.ip_forward" = 1;
  };

  # Restrict BGP TCP 179 listen port strictly to Top-of-Rack switch subnets (BGP-RADAR-007)
  networking.firewall.extraCommands = ''
    iptables -A INPUT -p tcp --dport 179 -s %s -j ACCEPT
    iptables -A INPUT -p tcp --dport 179 -j DROP
    ip6tables -A INPUT -p tcp --dport 179 -s fd00:100::/64 -j ACCEPT
    ip6tables -A INPUT -p tcp --dport 179 -j DROP
  '';
}
`, localASN, localASN, torSwitchSubnet)
}

// SynthesizeBGPAlertRule generates Prometheus alerting rules for BGP session drops and flap storms.
func SynthesizeBGPAlertRule() string {
	return `groups:
  - name: cilium-bgp-radar-alerts
    rules:
      - alert: CiliumBGPSessionDown
        expr: cilium_bgp_session_state != 6
        for: 1m
        labels:
          severity: critical
        annotations:
          summary: "Cilium BGP neighbor session is down"
          description: "BGP peer {{ $labels.peer_ip }} (ASN {{ $labels.peer_asn }}) is in non-established state."

      - alert: CiliumBGPRouteFlapStorm
        expr: rate(cilium_bgp_session_resets_total[1h]) > 5
        for: 5m
        labels:
          severity: high
        annotations:
          summary: "Cilium BGP route flapping detected"
          description: "BGP neighbor {{ $labels.peer_ip }} reset count exceeds 5 resets/hour."

      - alert: CiliumIPAMPoolExhaustionWarning
        expr: cilium_ipam_pool_allocated / cilium_ipam_pool_total > 0.85
        for: 5m
        labels:
          severity: high
        annotations:
          summary: "Cilium IPAM pool utilization exceeds 85%"
          description: "Pool {{ $labels.pool_name }} has fewer than 15% available IP addresses remaining."
`
}

// WriteSynthesizedPolicies persists generated BGP security manifests to the target directory.
func WriteSynthesizedPolicies(outDir string, policyName string, localASN, peerASN int, peerAddr, authSecret string) ([]string, error) {
	if outDir == "" {
		outDir = "policies/generated/bgp"
	}
	cleanDir := filepath.Clean(outDir)
	if err := os.MkdirAll(cleanDir, 0750); err != nil {
		return nil, fmt.Errorf("failed to create output directory %s: %w", cleanDir, err)
	}

	var written []string

	// 1. Cilium BGP Peering Policy
	k8sPolicy := SynthesizeHardenedCiliumBGPPolicy(policyName, localASN, peerASN, peerAddr, authSecret)
	k8sPath := filepath.Join(cleanDir, "cilium-bgp-hardened.yaml")
	if err := os.WriteFile(k8sPath, []byte(strings.TrimSpace(k8sPolicy)+"\n"), 0640); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", k8sPath, err)
	}
	written = append(written, k8sPath)

	// 2. NixOS FRR & Sysctl Module
	nixModule := SynthesizeHardenedNixOSBGPModule(localASN, "192.168.100.0/24")
	nixPath := filepath.Join(cleanDir, "nixos-bgp-peering-hardened.nix")
	if err := os.WriteFile(nixPath, []byte(strings.TrimSpace(nixModule)+"\n"), 0640); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", nixPath, err)
	}
	written = append(written, nixPath)

	// 3. Prometheus Alert Rules
	alertRule := SynthesizeBGPAlertRule()
	alertPath := filepath.Join(cleanDir, "bgp-alerts.yaml")
	if err := os.WriteFile(alertPath, []byte(strings.TrimSpace(alertRule)+"\n"), 0640); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", alertPath, err)
	}
	written = append(written, alertPath)

	return written, nil
}
