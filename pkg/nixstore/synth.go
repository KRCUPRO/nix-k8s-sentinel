// WriteSynthesizedPolicies writes hardened policies and Prometheus alert rules to target directory.
func WriteSynthesizedPolicies(outDir string, trustedKeys []string, substituters []string, trustedUsers []string) ([]string, error) {
	cleanDir := filepath.Clean(outDir)
	if err := os.MkdirAll(cleanDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create directory for synthesized store policies: %w", err)
	}

	written := make([]string, 0)

	// 1. nixos-store-hardened.nix
	nixModule := SynthesizeHardenedNixStoreModule(trustedKeys, substituters, trustedUsers)
	nixPath := filepath.Join(cleanDir, "nixos-store-hardened.nix")
	if err := os.WriteFile(nixPath, []byte(nixModule), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", nixPath, err)
	}
	written = append(written, nixPath)

	// 2. nix.conf
	confContent := SynthesizeNixConf(trustedKeys, substituters, trustedUsers)
	confPath := filepath.Join(cleanDir, "nix.conf")
	if err := os.WriteFile(confPath, []byte(confContent), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", confPath, err)
	}
	written = append(written, confPath)

	// 3. nixstore-alerts.yaml
	alerts := SynthesizeNixStoreAlertRules()
	alertsPath := filepath.Join(cleanDir, "nixstore-alerts.yaml")
	if err := os.WriteFile(alertsPath, []byte(alerts), 0644); err != nil {
		return nil, fmt.Errorf("failed to write %s: %w", alertsPath, err)
	}
	written = append(written, alertsPath)

	return written, nil
}
