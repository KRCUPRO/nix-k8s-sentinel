// SynthesizeHardenedNixOSEnclaveModule creates a declarative NixOS configuration module.
func SynthesizeHardenedNixOSEnclaveModule(cfg EnclavePeerConfig) string {
	iface := cfg.InterfaceName
	if iface == "" {
		iface = "wg0"
	}
	peerName := cfg.PeerName
	if peerName == "" {
		peerName = "confidential-peer-01"
	}
	platform := string(cfg.Platform)
	if platform == "" {
		platform = string(PlatformSEVSNP)
	}
	endpoint := cfg.Endpoint
	if endpoint == "" {
		endpoint = "192.168.100.10:51820"
	}
	pubKey := cfg.PublicKey
	if pubKey == "" {
		pubKey = "YWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWE="
	}

	pcrLines := []string{}
	pcrKeys := []int{0, 2, 4, 7}
	for _, k := range pcrKeys {
		val := cfg.RequiredPCRs[k]
		if val == "" {
			val = fmt.Sprintf("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b85%d", k)
		}
		pcrLines = append(pcrLines, fmt.Sprintf("          \"%d\" = \"%s\";", k, val))
	}

	return fmt.Sprintf(`# Hardened Confidential VM & Secure Enclave WireGuard Peer Policy
# Generated by nix-k8s-sentinel (v0.24.0)
{ config, pkgs, lib, ... }:

{
  networking.wireguard.interfaces.%s = {
    peers = [
      {
        # peer: %s
        publicKey = "%s";
        endpoint = "%s";
        allowedIPs = [ "10.100.0.0/24" ];
        persistentKeepalive = 25;

        # Confidential Computing Enclave Hardware Attestation Policy
        enclave = {
          enable = true;
          platform = "%s";
          minTcbSvn = %d;
          requireHardwareRoot = true;
          requireSessionKeyBinding = true;
          allowDebug = false;
          maxAttestationAgeSec = 3600;
          goldenImageDigest = "%s";
          pcrs = {
%s
          };
        };
      }
    ];
  };

  # Enforce pre-handshake kernel eBPF attestation gatekeeper
  systemd.services.wireguard-enclave-attestation = {
    description = "WireGuard Confidential Enclave Peer Attestation Daemon";
    after = [ "network.target" "wireguard-%s.service" ];
    wantedBy = [ "multi-user.target" ];
    serviceConfig = {
      Type = "simple";
      ExecStart = "${pkgs.bash}/bin/bash /var/run/wireguard/wg-enclave-gate.sh --interface %s";
      Restart = "always";
      RestartSec = "5s";
      MemoryDenyWriteExecute = true;
      ProtectSystem = "strict";
      ProtectHome = true;
      PrivateTmp = true;
    };
  };
}
`, iface, peerName, pubKey, endpoint, platform, cfg.MinTCBSVN, cfg.GoldenImageDigest, strings.Join(pcrLines, "\n"), iface, iface)
}

